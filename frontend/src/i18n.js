export function t(lang, key, vars) {
  const str = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key
  if (!vars) return str
  return Object.keys(vars).reduce(
    (acc, k) => acc.replaceAll(`{${k}}`, vars[k]),
    str
  )
}

